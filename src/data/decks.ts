import type { DeckConfig, StarterDeckPreset } from "../types.js";
import { validateMainDeck } from "./deckValidation.js";

type CardLine = readonly [cardId: string, count: number];

function copies(cardId: string, count: number): string[] {
  return Array.from({ length: count }, () => cardId);
}

function expandCardLines(lines: readonly CardLine[]): string[] {
  return lines.flatMap(([cardId, count]) => copies(cardId, count));
}

function validateDeck(mainDeck: string[], label = "deck"): void {
  const result = validateMainDeck(mainDeck);
  if (!result.valid) {
    throw new Error(`Invalid starter deck "${label}": ${result.errors.join(" ")}`);
  }
}

function defineDeck(mainDeck: string[], sideboard: string[]): DeckConfig {
  validateDeck(mainDeck, "starting deck");
  return { mainDeck: [...mainDeck], sideboard: [...sideboard] };
}

type StarterDeckPresetInput = Omit<StarterDeckPreset, "mainDeck"> & {
  cardLines: readonly CardLine[];
};

function definePreset({ cardLines, ...preset }: StarterDeckPresetInput): StarterDeckPreset {
  const mainDeck = expandCardLines(cardLines);
  validateDeck(mainDeck, preset.name);
  return { ...preset, mainDeck };
}


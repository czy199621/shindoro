export const STARTER_DECK_PRESETS_BY_CHARACTER = STARTER_DECK_PRESETS.reduce<Record<string, StarterDeckPreset[]>>(
  (groups, preset) => {
    groups[preset.characterId] = [...(groups[preset.characterId] ?? []), preset];
    return groups;
  },
  {}
);

export function getStarterDeckPresets(characterId: string): StarterDeckPreset[] {
  return STARTER_DECK_PRESETS_BY_CHARACTER[characterId] ?? STARTER_DECK_PRESETS_BY_CHARACTER.character_a;
}

export function getStarterDeckPreset(presetId: string): StarterDeckPreset | undefined {
  return STARTER_DECK_PRESETS.find((preset) => preset.id === presetId);
}

export function getDefaultStarterDeckPreset(characterId: string): StarterDeckPreset {
  return getStarterDeckPresets(characterId)[0] ?? STARTER_DECK_PRESETS[0];
}

export const STARTING_DECKS: Record<string, DeckConfig> = Object.fromEntries(
  Object.entries(STARTER_DECK_PRESETS_BY_CHARACTER).map(([characterId, presets]) => [
    characterId,
    defineDeck(presets[0]?.mainDeck ?? STARTER_DECK_PRESETS[0].mainDeck, PUBLIC_SIDEBOARD_FINISHERS)
  ])
) as Record<string, DeckConfig>;
